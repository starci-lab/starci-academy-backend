import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const home = path.dirname(fileURLToPath(import.meta.url));
const live = path.resolve(home, '../../.claude');
const candidate = path.join(home, 'final-candidate');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const json = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const run = json(path.join(home, 'integrated-run-1/result.json'));
if (run.status !== 'complete' || run.exitCode !== 0 || run.testedTreeUnchanged !== true) throw Error('Final integrated proof is not complete and green');
const tested = json(path.join(home, 'integrated-run-1/tested-tree.json'));
for (const [name, digest] of Object.entries(tested)) if (hash(fs.readFileSync(path.join(candidate, name))) !== digest) throw Error('Tested bytes changed: ' + name);
const log = fs.readFileSync(path.join(home, 'integrated-run-1/full.log'), 'utf8');
const counts = Object.fromEntries([...log.matchAll(/^ℹ (tests|pass|fail|skipped) (\d+)/gm)].map(row => [row[1], Number(row[2])]));
if (!counts.tests || counts.tests !== counts.pass || counts.fail || counts.skipped || !/\d+ generated files match the tree/.test(log)) throw Error('Final counts or generated docs failed');
const packHome = path.join(home, 'final-package');
const pack = json(path.join(packHome, 'readback.json'));
if (!pack.matches || hash(fs.readFileSync(path.join(packHome, 'starci-skills-2.5.0-rc.13.tgz'))) !== pack.archiveSha256) throw Error('Final package differs');
if (!fs.readFileSync(path.join(packHome, 'doctor.log'), 'utf8').includes('doctor: the installed tree validates')) throw Error('Install proof absent');
const git = (...args) => execFileSync('git', ['-C', live, ...args], { encoding: 'utf8', windowsHide: true }).trim();
if (git('rev-parse', 'HEAD') !== '749d3073c1f8b3effade0d6916fc7acaabc4f2b2' || git('write-tree') !== '51f0b0fc00f832cec56fec4619143ef0253e3916') throw Error('Live reviewed merge moved');
const names = ['scripts/plan-history.mjs', 'scripts/nested-return-fixture.mjs', 'scripts/restatement-reentry.spec.mjs'];
const normalized = bytes => bytes.toString('utf8').replace(/\r\n/g, '\n');
const entries = names.map(name => {
  const destination = path.join(live, name), base = path.join(home, 'merged-index', name);
  const old = fs.existsSync(destination) ? fs.readFileSync(destination) : null;
  if (fs.existsSync(base) ? !old || normalized(old) !== normalized(fs.readFileSync(base)) : old !== null) throw Error('Live patch path changed: ' + name);
  return { name, destination, bytes: fs.readFileSync(path.join(candidate, name)), before: old ? hash(old) : null };
});
const record = { adoptedAt: new Date().toISOString(), counts, testedTree: run.treeHash, package: pack, files: entries.map(entry => ({ path: entry.name, before: entry.before, after: hash(entry.bytes) })), published: false };
fs.writeFileSync(path.join(home, 'final-adoption.json'), JSON.stringify(record, null, 2) + '\n', { flag: 'wx' });
for (const entry of entries) fs.writeFileSync(entry.destination, entry.bytes);
for (const entry of entries) if (hash(fs.readFileSync(entry.destination)) !== hash(entry.bytes)) throw Error('Adoption readback differs');
console.log(JSON.stringify({ adopted: names, counts, published: false }));
